// Modal
function openModal(plan) {
  document.getElementById('contactModal').classList.remove('hidden');
  document.body.style.overflow = 'hidden';
  if (plan) {
    document.getElementById('planSelect').value = plan;
  }
}
function closeModal() {
  document.getElementById('contactModal').classList.add('hidden');
  document.body.style.overflow = '';
}
document.getElementById('contactModal').addEventListener('click', function(e) {
  if (e.target === this) closeModal();
});
document.addEventListener('keydown', function(e) {
  if (e.key === 'Escape') closeModal();
});

// FAQ
function toggleFaq(el) {
  const answer = el.nextElementSibling;
  const isOpen = answer.classList.contains('open');

  // Close all
  document.querySelectorAll('.faq-answer').forEach(a => a.classList.remove('open'));
  document.querySelectorAll('.faq-question').forEach(q => q.classList.remove('active'));

  if (!isOpen) {
    answer.classList.add('open');
    el.classList.add('active');
  }
}

// Form submission
document.getElementById('contactForm').addEventListener('submit', async function(e) {
  e.preventDefault();
  const btn = this.querySelector('button[type="submit"]');
  const msg = document.getElementById('formMessage');

  // Client-side validation (replaces browser-native validation)
  const name = this.querySelector('[name="name"]').value.trim();
  const email = this.querySelector('[name="email"]').value.trim();
  const errors = [];
  if (!name) errors.push('Name is required.');
  if (!email) {
    errors.push('Email is required.');
  } else if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
    errors.push('Please enter a valid email address.');
  }
  // Check Turnstile CAPTCHA
  const turnstileResponse = this.querySelector('[name="cf-turnstile-response"]');
  if (!turnstileResponse || !turnstileResponse.value) {
    errors.push('Please complete the security check.');
  }
  if (errors.length) {
    msg.className = 'mb-4 p-3 rounded-lg text-sm bg-red-50 text-red-700 border border-red-200';
    msg.textContent = errors.join(' ');
    msg.classList.remove('hidden');
    return;
  }

  btn.disabled = true;
  btn.innerHTML = 'Sending...';

  const formData = new FormData(this);
  const data = Object.fromEntries(formData);
  data.source = 'websites-page';

  try {
    const response = await fetch('contact.php', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(data)
    });
    const result = await response.json();

    if (result.success) {
      msg.className = 'mb-4 p-3 rounded-lg text-sm bg-green-50 text-green-700 border border-green-200';
      msg.textContent = "Thanks! We'll be in touch within 24 hours.";
      msg.classList.remove('hidden');
      this.reset();
    } else {
      throw new Error(result.message || 'Something went wrong');
    }
  } catch (error) {
    msg.className = 'mb-4 p-3 rounded-lg text-sm bg-red-50 text-red-700 border border-red-200';
    msg.textContent = error.message || 'Something went wrong. Please try again or call us directly.';
    msg.classList.remove('hidden');
  }

  btn.disabled = false;
  btn.innerHTML = 'Submit Request <svg xmlns="http://www.w3.org/2000/svg" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><line x1="5" y1="12" x2="19" y2="12"/><polyline points="12 5 19 12 12 19"/></svg>';
});
